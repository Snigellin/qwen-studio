  function currentLocale() {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'zh-CN' || stored === 'en') return stored;
    return /^zh/i.test(navigator.language || '') ? 'zh-CN' : 'en';
  }

  function t(key, vars) {
    const locale = currentLocale();
    let value = (locale === 'zh-CN' ? (zh[key] || en[key]) : en[key]) || key;
    if (vars) {
      for (const name of Object.keys(vars)) {
        value = value.split('{' + name + '}').join(String(vars[name]));
      }
    }
    return value;
  }

  function apply() {
    const locale = currentLocale();
    document.documentElement.lang = locale === 'zh-CN' ? 'zh-CN' : 'en';
    document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.getAttribute('data-i18n-placeholder')); });
    document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.getAttribute('data-i18n-title')); });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });
  }

  function setLocale(locale) {
    if (locale !== 'zh-CN' && locale !== 'en') return;
    localStorage.setItem(STORAGE_KEY, locale);
    apply();
    window.dispatchEvent(new CustomEvent('qwen:locale-changed'));
  }

  window.qwenI18n = { t, apply, setLocale, currentLocale, LOCALES: { en, 'zh-CN': zh } };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', apply);
  } else {
    apply();
  }
